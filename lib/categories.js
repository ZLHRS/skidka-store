export const CATEGORIES=[
 {id:'all',label:'Всё'},
 {id:'sweets',label:'Сладости'},
 {id:'drinks',label:'Напитки'},
 {id:'dairy',label:'Молочное'},
 {id:'meat',label:'Мясо и рыба'},
 {id:'food',label:'Продукты'},
 {id:'home',label:'Для дома'}
];
export function categoryForProduct(product){
 const name=String(product.name||'').normalize('NFKC').toLocaleLowerCase('ru').trim();
 if(/паста зуб|шампун|краска для волос|стиральн|порошок|дезодорант|прокладк|подгузник|салфет|мыло|^корм\s|кондиционер|моющ|чистящ|зубн|губк|для (лица|тела|рук|посуды|белья|душа|волос)|туалетн|бритв|наполнитель/.test(name))return 'home';
 if(/^(напиток|чай|кофе|сок|вода|нектар|какао|компот)(\s|$)|лимонад/.test(name))return 'drinks';
 if(/^молоко|^сыр(ок)?(\s|$)|^сметана|^биойогурт|^йогурт|^кефир|^творог|^сливки|^ряженка|^айран|^масло.*(сливоч|традиционное)|^коктейль.*молочн/.test(name))return 'dairy';
 if(/^(завтрак|хлопья|мюсли)(\s|$)/.test(name))return 'food';
 if(/конфет|шоколад|печенье|печенья|вафл|мармелад|зефир|пастил|карамел|пирожн|торт|маффин|^морожен|пломбир|батончик|nutella|нутелл|пряник|бисквит|^паста.*(орехов|какао)|^рулет.*(арахис|бисквит|крем)/.test(name))return 'sweets';
 if(/^(шпрот|тунец|колбас|сосиск|говядин|филе|окороч|мясо|куриц|рыба|лосос|форел|фарш|котлет|ветчин|кревет|сельд|скумбр|печень\s)/.test(name))return 'meat';
 return 'food';
}
